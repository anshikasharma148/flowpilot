"""Monitoring Agent - answers status questions and manages schedules from chat.

All answers are built from the database (never generated by the LLM), so numbers
are always exact. The LLM / rules only decide *what* is being asked.
"""
from collections import Counter
from datetime import datetime, timezone

from sqlalchemy.orm import Session

from .. import scheduler
from ..data_sources import load_alerts
from ..db import EmailLog, Schedule, Ticket, Workflow, WorkflowRun

TOPICS = ("last_run", "run", "recent_runs", "failed_runs", "schedules", "tickets", "emails", "alerts", "stats")
SCHEDULE_OPS = ("pause", "resume", "delete", "run_now")


def _ago(dt: datetime | None) -> str:
    if not dt:
        return "never"
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    s = (datetime.now(timezone.utc) - dt).total_seconds()
    if s < 60:
        return "just now"
    if s < 3600:
        return f"{int(s // 60)} min ago"
    if s < 86400:
        return f"{int(s // 3600)} h ago"
    return f"{int(s // 86400)} d ago"


def _fmt_local(dt: datetime | None) -> str:
    if not dt:
        return "n/a"
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt.astimezone(scheduler.TZ).strftime("%Y-%m-%d %H:%M")


def _run_detail(r: WorkflowRun) -> str:
    dur = f"{(r.finished_at - r.started_at).total_seconds():.1f}s" if r.finished_at else "running"
    lines = [f"**Run #{r.id} - {r.workflow.code} {r.workflow.name}**: **{r.status.upper()}** "
             f"(trigger: {r.trigger}, {_ago(r.started_at)}, took {dur})", "",
             "| Step | Status | Note |", "|---|---|---|"]
    for s in r.steps:
        note = s.error or ((s.output or {}).get("reason", "") if isinstance(s.output, dict) else "")
        lines.append(f"| {s.step_id} (`{s.plugin}.{s.action}`) | {s.status} | {str(note)[:90]} |")
    actions = [ln for ln in (r.report or "").splitlines() if ln.startswith("- ")]
    if actions:
        lines += ["", "**Actions taken:**", *actions]
    if r.error:
        lines += ["", f"**Error:** {r.error}"]
    return "\n".join(lines)


def _runs_table(runs: list[WorkflowRun]) -> str:
    lines = ["| Run | Workflow | Status | Trigger | When |", "|---|---|---|---|---|"]
    lines += [f"| #{r.id} | {r.workflow.code} {r.workflow.name} | {r.status} | {r.trigger} | {_ago(r.started_at)} |"
              for r in runs]
    return "\n".join(lines)


def answer(db: Session, topic: str, target_id: int | None = None, limit: int = 10) -> tuple[str, dict]:
    meta: dict = {}
    if topic == "last_run" or (topic == "run" and not target_id):
        r = db.query(WorkflowRun).order_by(WorkflowRun.id.desc()).first()
        if not r:
            return "No workflows have run yet.", meta
        meta["run_id"] = r.id
        return "Here is the most recent run:\n\n" + _run_detail(r), meta
    if topic == "run":
        r = db.get(WorkflowRun, target_id)
        if not r:
            return f"I couldn't find run #{target_id}.", meta
        meta["run_id"] = r.id
        return _run_detail(r), meta
    if topic in ("recent_runs", "failed_runs"):
        q = db.query(WorkflowRun).order_by(WorkflowRun.id.desc())
        if topic == "failed_runs":
            q = q.filter(WorkflowRun.status.in_(["failed", "partial"]))
        runs = q.limit(limit).all()
        if not runs:
            return ("No failed or partial runs - everything has succeeded so far."
                    if topic == "failed_runs" else "No workflows have run yet."), meta
        total = db.query(WorkflowRun).count()
        by_status = Counter(s for (s,) in db.query(WorkflowRun.status).all())
        head = (f"**{len(runs)} most recent {'failed/partial ' if topic == 'failed_runs' else ''}run(s)** "
                f"(all time: {total} runs - " + ", ".join(f"{v} {k}" for k, v in by_status.items()) + ")")
        return head + "\n\n" + _runs_table(runs), meta
    if topic == "schedules":
        items = db.query(Schedule).order_by(Schedule.id).all()
        if not items:
            return "There are no schedules yet. Try *\"Every day at 9 AM summarise down alerts\"*.", meta
        lines = [f"**{sum(s.enabled for s in items)} active / {len(items)} total schedule(s):**", "",
                 "| # | Workflow | When | Next run | Last run | Status |", "|---|---|---|---|---|---|"]
        for s in items:
            nxt = scheduler.next_run(s.id)
            lines.append(f"| {s.id} | {s.workflow.code} {s.workflow.name} | {scheduler.describe(s)} | "
                         f"{nxt.strftime('%Y-%m-%d %H:%M') if nxt else '-'} | {_ago(s.last_run_at)} | "
                         f"{'active' if s.enabled else 'paused'} |")
        lines += ["", "You can say *\"pause schedule 1\"*, *\"resume schedule 1\"*, *\"run schedule 1 now\"* "
                      "or *\"delete schedule 1\"*."]
        return "\n".join(lines), meta
    if topic == "tickets":
        tickets = db.query(Ticket).order_by(Ticket.id.desc()).all()
        if not tickets:
            return "No tickets have been created yet.", meta
        today = datetime.now(scheduler.TZ).date()
        n_today = sum(1 for t in tickets if (t.created_at.replace(tzinfo=timezone.utc) if t.created_at.tzinfo is None
                                             else t.created_at).astimezone(scheduler.TZ).date() == today)
        lines = [f"**{len(tickets)} ticket(s) created** ({n_today} today):", "",
                 "| Ticket | Priority | Device | Status | Created |", "|---|---|---|---|---|"]
        lines += [f"| {t.key} | {t.priority} | {t.device} | {t.status} | {_ago(t.created_at)} |"
                  for t in tickets[:limit]]
        return "\n".join(lines), meta
    if topic == "emails":
        emails = db.query(EmailLog).order_by(EmailLog.id.desc()).all()
        if not emails:
            return "No emails have been sent yet.", meta
        lines = [f"**{len(emails)} email(s)** ("
                 + ", ".join(f"{v} {k}" for k, v in Counter(e.status for e in emails).items()) + "):", "",
                 "| To | Subject | Status | When |", "|---|---|---|---|"]
        lines += [f"| {e.to} | {e.subject[:60]} | {e.status} | {_ago(e.created_at)} |" for e in emails[:limit]]
        return "\n".join(lines), meta
    if topic == "alerts":
        alerts = load_alerts()
        by_int = Counter((a.get("intensity") or "").upper() for a in alerts)
        unticketed_down = [a for a in alerts if (a.get("intensity") or "").upper() == "DOWN" and not a.get("ticket_id")]
        local = {t.alert_uid for t in db.query(Ticket).all()}
        unticketed_down = [a for a in unticketed_down if a.get("uid") not in local]
        lines = [f"**{len(alerts)} active alert(s)**: " + ", ".join(f"{v} {k}" for k, v in by_int.most_common()),
                 f"DOWN alerts without a ticket: **{len(unticketed_down)}**", "",
                 "| Device | Metric | Severity | Active (min) | Ticket |", "|---|---|---|---|---|"]
        lines += [f"| {a.get('device/link')} | {a.get('metric')} | {a.get('intensity')} | {a.get('active_since')} | "
                  f"{a.get('ticket_id') or '-'} |" for a in alerts]
        return "\n".join(lines), meta
    # stats / overview
    runs = db.query(WorkflowRun).count()
    by_status = Counter(s for (s,) in db.query(WorkflowRun.status).all())
    last = db.query(WorkflowRun).order_by(WorkflowRun.id.desc()).first()
    nxt_runs = [(scheduler.next_run(s.id), s) for s in db.query(Schedule).filter_by(enabled=True).all()]
    nxt_runs = sorted([x for x in nxt_runs if x[0]], key=lambda x: x[0])
    lines = ["**Automation overview**", "",
             "| Metric | Value |", "|---|---|",
             f"| Workflows | {db.query(Workflow).filter_by(is_active=True).count()} |",
             f"| Runs | {runs} (" + (", ".join(f"{v} {k}" for k, v in by_status.items()) or "none") + ") |",
             f"| Last run | " + (f"#{last.id} {last.workflow.code} - {last.status}, {_ago(last.started_at)}" if last else "-") + " |",
             f"| Active schedules | {len(nxt_runs)} |",
             f"| Next scheduled run | " + (f"{nxt_runs[0][0].strftime('%Y-%m-%d %H:%M')} ({nxt_runs[0][1].workflow.code})"
                                         if nxt_runs else "-") + " |",
             f"| Tickets created | {db.query(Ticket).count()} |",
             f"| Emails | {db.query(EmailLog).count()} |",
             f"| Active alerts | {len(load_alerts())} |"]
    return "\n".join(lines), meta


def manage_schedule(db: Session, op: str, schedule_id: int | None) -> tuple[str, dict]:
    if not schedule_id:
        reply, meta = answer(db, "schedules")
        return "Which schedule? Please give its number.\n\n" + reply, meta
    s = db.get(Schedule, schedule_id)
    if not s:
        return f"Schedule #{schedule_id} doesn't exist. " + answer(db, "schedules")[0], {}
    label = f"schedule #{s.id} ({s.workflow.code} {s.workflow.name}, {scheduler.describe(s)})"
    if op == "pause":
        if not s.enabled:
            return f"{label[0].upper() + label[1:]} is already paused.", {"schedule_id": s.id}
        s.enabled = False
        db.commit()
        scheduler.unregister(s.id)
        return f"Paused {label}. It won't run until you resume it.", {"schedule_id": s.id}
    if op == "resume":
        s.enabled = True
        db.commit()
        scheduler.register(s)
        nxt = scheduler.next_run(s.id)
        return (f"Resumed {label}. Next run: **{nxt.strftime('%Y-%m-%d %H:%M') if nxt else 'n/a'}**.",
                {"schedule_id": s.id})
    if op == "delete":
        scheduler.unregister(s.id)
        db.query(WorkflowRun).filter_by(schedule_id=s.id).update({"schedule_id": None})
        db.delete(s)
        db.commit()
        return f"Deleted {label}. Its past runs are kept in the run history.", {}
    if op == "run_now":
        from ..engine.executor import execute_workflow
        run = execute_workflow(db, s.workflow, s.params, trigger="schedule", schedule_id=s.id)
        s.last_run_at = run.started_at
        db.commit()
        return (f"Ran {label} now.\n\n" + _run_detail(run), {"run_id": run.id, "schedule_id": s.id})
    return f"Unsupported schedule operation '{op}'.", {}

